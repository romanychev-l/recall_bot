"""SQLAlchemy models.

Two schema decisions worth knowing about:

1. ``UserCard.due`` is denormalized out of the ``fsrs`` JSON blob into a real
   column so ``(user_id, due)`` can be indexed. Filtering on a key *inside* JSON
   is awkward and backend-specific; a plain column behaves identically on SQLite
   and Postgres. The repo keeps both in sync on every write.

2. ``User.current_batch_id`` is a plain integer, not a foreign key. A real FK
   would make users and batches reference each other in a cycle, and resolving
   that at CREATE TABLE time needs ALTER TABLE ADD CONSTRAINT, which SQLite does
   not support.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Optional

from sqlalchemy import (
    JSON,
    BigInteger,
    Boolean,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    MetaData,
    String,
    Text,
    TypeDecorator,
    UniqueConstraint,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from bot.constants import (
    DEFAULT_BATCH_SIZE,
    DEFAULT_DAILY_GOAL,
    DEFAULT_REMINDER_TIME,
    DEFAULT_TZ,
    STATE_NEW,
)

# Explicit constraint names — Alembic's SQLite batch mode needs them to rebuild
# tables, since SQLite cannot drop an unnamed constraint.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class UtcDateTime(TypeDecorator):
    """Store and return tz-aware UTC datetimes on any backend.

    SQLite has no native datetime type: SQLAlchemy writes an ISO string without
    an offset, so a tz-aware value read back would be naive. Mixing naive and
    aware datetimes is what broke card review before (fix f38f4a6), so normalize
    in both directions and keep the whole app tz-aware.
    """

    impl = DateTime(timezone=True)
    cache_ok = True

    def process_bind_param(
        self, value: Optional[datetime], dialect: Any
    ) -> Optional[datetime]:
        if value is None:
            return None
        if value.tzinfo is None:
            return value.replace(tzinfo=timezone.utc)
        return value.astimezone(timezone.utc)

    def process_result_value(
        self, value: Optional[datetime], dialect: Any
    ) -> Optional[datetime]:
        if value is None:
            return None
        if value.tzinfo is None:
            return value.replace(tzinfo=timezone.utc)
        return value.astimezone(timezone.utc)


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class User(Base):
    __tablename__ = "users"

    # Telegram user id — assigned by Telegram, never generated by us.
    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=False)
    batch_size: Mapped[int] = mapped_column(Integer, default=DEFAULT_BATCH_SIZE)
    daily_goal: Mapped[int] = mapped_column(Integer, default=DEFAULT_DAILY_GOAL)
    reminder_time: Mapped[str] = mapped_column(String(5), default=DEFAULT_REMINDER_TIME)
    tz: Mapped[str] = mapped_column(String(64), default=DEFAULT_TZ)
    language: Mapped[str] = mapped_column(String(8), default="ru")
    initial_rank: Mapped[int] = mapped_column(Integer, default=0)
    current_batch_id: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    next_batch_start_rank: Mapped[int] = mapped_column(Integer, default=0)
    streak_days: Mapped[int] = mapped_column(Integer, default=0)
    last_session_date: Mapped[Optional[datetime]] = mapped_column(
        UtcDateTime, nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(UtcDateTime)


class Word(Base):
    __tablename__ = "words"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    english: Mapped[str] = mapped_column(String(128), index=True)
    translation: Mapped[str] = mapped_column(Text)
    frequency_rank: Mapped[int] = mapped_column(Integer, unique=True, index=True)
    pos: Mapped[str] = mapped_column(String(32), default="")
    example: Mapped[str] = mapped_column(Text, default="")
    is_phrasal: Mapped[bool] = mapped_column(Boolean, default=False)


class Batch(Base):
    __tablename__ = "batches"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    created_at: Mapped[datetime] = mapped_column(UtcDateTime)


class UserCard(Base):
    __tablename__ = "user_cards"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="CASCADE")
    )
    word_id: Mapped[int] = mapped_column(ForeignKey("words.id", ondelete="CASCADE"))
    batch_id: Mapped[int] = mapped_column(ForeignKey("batches.id", ondelete="CASCADE"))
    frequency_rank: Mapped[int] = mapped_column(Integer)
    # Full FSRS state. Datetimes inside are ISO strings — SrsService already
    # parses those back (see _card_from_doc).
    fsrs: Mapped[dict[str, Any]] = mapped_column(JSON)
    # Mirror of fsrs["due"], kept in sync on write so it can be indexed.
    due: Mapped[datetime] = mapped_column(UtcDateTime)
    my_state: Mapped[str] = mapped_column(String(16), default=STATE_NEW)
    consecutive_successes_at_review: Mapped[int] = mapped_column(Integer, default=0)
    first_reached_review_at: Mapped[Optional[datetime]] = mapped_column(
        UtcDateTime, nullable=True
    )
    is_hard: Mapped[bool] = mapped_column(Boolean, default=False)
    skip_until: Mapped[Optional[datetime]] = mapped_column(UtcDateTime, nullable=True)
    created_at: Mapped[datetime] = mapped_column(UtcDateTime)
    updated_at: Mapped[datetime] = mapped_column(UtcDateTime)

    __table_args__ = (
        UniqueConstraint("user_id", "word_id", name="uq_user_cards_user_id_word_id"),
        Index("ix_user_cards_user_id_due", "user_id", "due"),
        Index(
            "ix_user_cards_user_id_batch_id_my_state",
            "user_id",
            "batch_id",
            "my_state",
        ),
    )


class ReviewLog(Base):
    __tablename__ = "review_log"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="CASCADE")
    )
    word_id: Mapped[int] = mapped_column(ForeignKey("words.id", ondelete="CASCADE"))
    batch_id: Mapped[int] = mapped_column(ForeignKey("batches.id", ondelete="CASCADE"))
    result: Mapped[str] = mapped_column(String(8))
    user_input: Mapped[str] = mapped_column(Text)
    reviewed_at: Mapped[datetime] = mapped_column(UtcDateTime)

    __table_args__ = (
        Index("ix_review_log_user_id_reviewed_at", "user_id", "reviewed_at"),
    )
